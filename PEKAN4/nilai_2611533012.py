# Program konversi nilai angka menjadi huruf

nilai_3012 = int(input("input nilai angka: "))

if nilai_3012 >= 81:
    print("A")
elif nilai_3012 >= 70:
    print("B")
elif nilai_3012 >= 60:
    print("C")
elif nilai_3012 >= 50:
    print("D")
else:
    print("E")
